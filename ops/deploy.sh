#!/usr/bin/env bash
# First install AND every update:  ./ops/deploy.sh
# Builds the images, applies database migrations, creates the owner account on first run,
# and (re)starts everything. Safe to run repeatedly. Also run by the in-app updater.
set -euo pipefail
export MSYS_NO_PATHCONV=1   # Git Bash on Windows: keep /container/paths as they are
cd "$(dirname "$0")/.."
[ -f .env.production ] || { echo "Missing .env.production (copy .env.production.example and fill it in)"; exit 1; }

# Secrets shared by the app and its internal helper containers (created once)
for name in UPDATER_TOKEN WHATSAPP_TOKEN BACKUP_TOKEN; do
  if ! grep -q "^${name}=.\+" .env.production; then
    printf '\n# Internal secret (generated by ops/deploy.sh)\n%s=%s\n' "$name" "$(openssl rand -hex 32)" >> .env.production
    echo "==> Created ${name} in .env.production"
  fi
done

# Which code is being deployed (shown in the app, used to detect new releases)
export APP_COMMIT="$(git rev-parse --short HEAD 2>/dev/null || echo unknown)"
export APP_BUILT_AT="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
echo "==> Deploying version $(sed -n 's/.*"version": *"\([^"]*\)".*/\1/p' package.json | head -1) (commit ${APP_COMMIT})"

DC="docker compose --env-file .env.production -f docker-compose.prod.yml"

echo "==> Building images"
$DC --profile tools build

echo "==> Starting database"
$DC up -d db

echo "==> Applying database migrations (platform + every bureau)"
$DC --profile tools run --rm tools

echo "==> Starting app, web server and backups"
if [ "${RUNNING_IN_UPDATER:-}" = "1" ]; then
  # Started from the app's Update button: don't restart the updater that is running this script
  # (whatsapp only restarts if its code changed; the linked number survives restarts)
  $DC up -d app caddy backup whatsapp
else
  $DC up -d app caddy backup whatsapp updater
fi

echo "==> Waiting for the app"
for i in $(seq 1 30); do
  if $DC exec -T app node -e "fetch('http://127.0.0.1:3000/api/health').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))" 2>/dev/null; then
    echo "App is healthy (commit ${APP_COMMIT})."
    $DC ps
    exit 0
  fi
  sleep 2
done
echo "App did not become healthy. Logs:"; $DC logs --tail 50 app; exit 1
