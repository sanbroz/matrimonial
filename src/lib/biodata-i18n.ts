/** Translate a stored value for display; lists ("Sikh, Hindu") are translated item by item. */
export function tv(value: string | null | undefined, lang: Lang): string {
  if (value == null) return "";
  if (lang === "en") return value;
  const direct = VALUES[value.trim().toLowerCase()];
  if (direct) return direct;
  if (value.includes(",")) return value.split(",").map((v) => tv(v.trim(), lang)).join(", ");
  return value;
}
